create or replace function public.subscribe_to_rugvaya_newsletter(p_email text)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  normalized_email text := lower(trim(coalesce(p_email, '')));
begin
  if length(normalized_email) < 5 or length(normalized_email) > 254
     or normalized_email !~ '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$' then
    raise exception 'Enter a valid email address';
  end if;

  insert into public.newsletter_subscribers(email)
  values (normalized_email)
  on conflict (email) do update
    set is_active = true;
end;
$$;
revoke all on function public.subscribe_to_rugvaya_newsletter(text) from public;
grant execute on function public.subscribe_to_rugvaya_newsletter(text) to anon, authenticated;

