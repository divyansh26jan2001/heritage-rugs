-- Seller order views are granted without creating a customer/order RLS loop.
create or replace function public.is_seller_order(p_order_id uuid)
returns boolean
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select exists (
    select 1 from public.order_items oi
    join public.shops s on s.id = oi.shop_id
    where oi.order_id = p_order_id
      and s.owner_id = (select auth.uid())
  );
$$;

drop policy if exists "orders_seller_read" on public.orders;
create policy "orders_seller_read" on public.orders
for select to authenticated
using (public.is_seller_order(id));

drop policy if exists "order_items_customer_seller_or_admin_read" on public.order_items;
create policy "order_items_customer_seller_or_admin_read"
on public.order_items for select
to authenticated
using (
  public.is_shop_owner(shop_id)
  or public.is_admin()
  or exists (
    select 1 from public.orders o
    where o.id = order_items.order_id
      and o.customer_id = (select auth.uid())
  )
);

-- Secure checkout RPC: database calculates prices/totals, validates stock and
-- approved-shop status, locks inventory rows, and records an unpaid order.
create or replace function public.create_rugvaya_order(
  p_customer_name text,
  p_customer_phone text,
  p_shipping_address jsonb,
  p_items jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_user_id uuid := auth.uid();
  v_email text;
  v_item jsonb;
  v_product public.products%rowtype;
  v_product_id uuid;
  v_quantity integer;
  v_subtotal numeric(12,2) := 0;
  v_snapshots jsonb := '[]'::jsonb;
  v_order public.orders%rowtype;
  v_line jsonb;
begin
  if v_user_id is null then
    raise exception 'Please sign in before placing an order';
  end if;
  if length(trim(coalesce(p_customer_name, ''))) < 2 then
    raise exception 'Enter your full name';
  end if;
  if length(trim(coalesce(p_customer_phone, ''))) < 6 then
    raise exception 'Enter a valid phone number';
  end if;
  if p_shipping_address is null or jsonb_typeof(p_shipping_address) <> 'object'
     or coalesce(trim(p_shipping_address->>'line1'), '') = ''
     or coalesce(trim(p_shipping_address->>'city'), '') = ''
     or coalesce(trim(p_shipping_address->>'country'), '') = '' then
    raise exception 'Complete the shipping address';
  end if;
  if p_items is null or jsonb_typeof(p_items) <> 'array'
     or jsonb_array_length(p_items) < 1 or jsonb_array_length(p_items) > 30 then
    raise exception 'Your cart is empty or contains too many items';
  end if;

  select lower(email) into v_email from auth.users where id = v_user_id;
  if v_email is null then raise exception 'Could not verify the signed-in email'; end if;

  for v_item in select value from jsonb_array_elements(p_items) as x(value) loop
    begin
      v_product_id := (v_item->>'product_id')::uuid;
      v_quantity := (v_item->>'quantity')::integer;
    exception when others then
      raise exception 'A cart item is invalid';
    end;

    if v_quantity < 1 or v_quantity > 10 then
      raise exception 'Quantity must be between 1 and 10';
    end if;

    select p.* into v_product
    from public.products p
    join public.shops s on s.id = p.shop_id
    where p.id = v_product_id
      and p.status = 'published'
      and p.stock >= v_quantity
      and s.status = 'approved'
    for update of p;

    if not found then
      raise exception 'A rug is unavailable or no longer has enough stock. Refresh your cart.';
    end if;

    update public.products set stock = stock - v_quantity where id = v_product.id;
    v_subtotal := v_subtotal + (v_product.price * v_quantity);
    v_snapshots := v_snapshots || jsonb_build_array(jsonb_build_object(
      'product_id', v_product.id,
      'shop_id', v_product.shop_id,
      'product_name', v_product.name,
      'quantity', v_quantity,
      'unit_price', v_product.price
    ));
  end loop;

  insert into public.orders (
    customer_id, customer_name, customer_email, customer_phone,
    shipping_address, currency, subtotal, total, status, payment_status
  )
  values (
    v_user_id, trim(p_customer_name), v_email, trim(p_customer_phone),
    p_shipping_address, 'USD', v_subtotal, v_subtotal, 'pending', 'unpaid'
  )
  returning * into v_order;

  for v_line in select value from jsonb_array_elements(v_snapshots) as x(value) loop
    insert into public.order_items (
      order_id, product_id, shop_id, product_name, quantity, unit_price, line_total
    )
    values (
      v_order.id,
      (v_line->>'product_id')::uuid,
      (v_line->>'shop_id')::uuid,
      v_line->>'product_name',
      (v_line->>'quantity')::integer,
      (v_line->>'unit_price')::numeric,
      (v_line->>'unit_price')::numeric * (v_line->>'quantity')::integer
    );
  end loop;

  return jsonb_build_object(
    'id', v_order.id,
    'order_number', v_order.order_number,
    'subtotal', v_subtotal,
    'total', v_subtotal,
    'currency', 'USD',
    'status', v_order.status,
    'payment_status', v_order.payment_status
  );
end;
